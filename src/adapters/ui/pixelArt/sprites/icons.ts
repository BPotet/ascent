/** Le nom d'une icône. */
export type IconName = keyof typeof DRAWN | 'right';

/** Les lignes d'une icône, de haut en bas. */
export type IconRows = readonly string[];

const mirrored = (rows: IconRows): IconRows => rows.map((row) => [...row].reverse().join(''));

/** La table des icônes : « right » est le miroir de « left ». */
export const ICONS: Readonly<Record<IconName, IconRows>> = {
  ...DRAWN,
  right: mirrored(DRAWN.left),
};

/** Les noms de toutes les icônes. */
export const iconNames = Object.keys(ICONS) as IconName[];
